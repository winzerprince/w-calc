"""Generate reference vectors for engine functions with mpmath (dev tool).

Usage: python tool/gen_function_vectors.py > packages/wcalc_engine/test/number/function_vectors.dart
Requires: pip install mpmath
"""
from decimal import Decimal, ROUND_HALF_UP, getcontext
import mpmath as mp

mp.mp.dps = 60
getcontext().prec = 80

def r15(v):
    """Round to 15 significant digits half-up, format like Dec.toString()."""
    d = Decimal(mp.nstr(v, 50, min_fixed=-200, max_fixed=200))
    if d == 0 or abs(d) < Decimal('1e-99'):
        return '0'  # device underflows below 1e-99
    q = d.quantize(Decimal(1).scaleb(d.adjusted() - 14), rounding=ROUND_HALF_UP)
    s = format(q.normalize(), 'f')
    if '.' in s:
        s = s.rstrip('0').rstrip('.')
    return s

ERR = 'ERR'
UNIT = {'deg': mp.pi / 180, 'rad': mp.mpf(1), 'gra': mp.pi / 200}

def trig(f, x, u):
    a = mp.mpf(x) * UNIT[u]
    # Exact quadrant handling like the device (Deg/Gra multiples of 90°/100g).
    quarter = {'deg': 90, 'gra': 100}.get(u)
    if quarter and (mp.mpf(x) / quarter) == int(mp.mpf(x) / quarter):
        k = int(mp.mpf(x) / quarter) % 4
        s, c = [(0, 1), (1, 0), (0, -1), (-1, 0)][k]
        if f == 'sin': return r15(s)
        if f == 'cos': return r15(c)
        return ERR if c == 0 else r15(mp.mpf(s) / c)
    return r15({'sin': mp.sin, 'cos': mp.cos, 'tan': mp.tan}[f](a))

def inv(f, x, u):
    v = {'asin': mp.asin, 'acos': mp.acos, 'atan': mp.atan}[f](mp.mpf(x))
    return r15(v / UNIT[u])

cases = []
for u in ['deg', 'rad', 'gra']:
    for x in ['0', '30', '45', '60', '90', '180', '270', '-35', '1', '0.5', '123.456', '1e-5', '-720.25', '89.9999', '1000000']:
        for f in ['sin', 'cos', 'tan']:
            cases.append((f, u, [x], trig(f, x, u)))
    for x in ['0', '0.5', '-0.5', '1', '-1', '0.741', '1e-7', '0.999999']:
        for f in ['asin', 'acos']:
            cases.append((f, u, [x], inv(f, x, u)))
    for x in ['0', '0.741', '-1', '1e10', '-3.5', '1e-20']:
        cases.append(('atan', u, [x], inv('atan', x, u)))

def add(f, xs, fn):
    for x in xs:
        try:
            v = fn(*[mp.mpf(a) for a in x]) if isinstance(x, tuple) else fn(mp.mpf(x))
            cases.append((f, None, list(x) if isinstance(x, tuple) else [x], r15(v)))
        except Exception:
            cases.append((f, None, list(x) if isinstance(x, tuple) else [x], ERR))

add('sinh', ['3.6', '0', '1e-10', '-2.5', '230', '0.001'], mp.sinh)
add('cosh', ['0', '1.5', '-20', '230'], mp.cosh)
add('tanh', ['0.5', '-3', '1e-9', '25'], mp.tanh)
add('asinh', ['30', '0', '1e-12', '-0.75', '1e50'], mp.asinh)
add('acosh', ['1', '2', '1e40'], mp.acosh)
add('atanh', ['0.5', '-0.999', '1e-15'], mp.atanh)
add('ln', ['90', '2', '0.001', '1e99', '1e-99', '2.71828182845904', '1.0000001'], mp.ln)
add('log', ['1.23', '1000', '2', '0.5', '9.99999999999999e99', '1e-50'], mp.log10)
add('exp', ['10', '-1', '0.001', '230', '-230', '1e-10'], mp.exp)
add('tenPow', ['1.5', '-2.5', '0.30103', '99.5'], lambda x: mp.power(10, x))
add('sqrt', ['2', '3', '5', '0.0004', '1e99', '123456789'], mp.sqrt)
add('cbrt', ['5', '-27', '0.001', '2', '1e-50', '-1234.5'], lambda x: mp.sign(x) * mp.cbrt(abs(x)))
add('pow', [('2', '-3'), ('-2', '4'), ('2', '0.5'), ('1.5', '2.5'), ('10', '-99'), ('7', '30'), ('0.5', '100'), ('-8', '3')], mp.power)
add('xroot', [('7', '123'), ('5', '32'), ('4', '0.0016'), ('2.5', '10')], lambda a, b: mp.power(b, 1 / a))
add('fact', ['0', '1', '5', '8', '20', '69'], mp.factorial)
add('nPr', [('7', '4'), ('10', '0'), ('100', '20'), ('9999999999', '3')], lambda n, r: mp.factorial(n) / mp.factorial(n - r))
add('nCr', [('10', '4'), ('50', '25'), ('9999999999', '2'), ('300', '150')], lambda n, r: mp.binomial(n, r))

print('// GENERATED by tool/gen_function_vectors.py (mpmath). Do not edit by hand.')
print('// (function, angle unit or null, args, expected 15-digit value or ERR)')
print('const functionVectors = <(String, String?, List<String>, String)>[')
for f, u, xs, e in cases:
    us = 'null' if u is None else f"'{u}'"
    args = ', '.join(f"'{a}'" for a in xs)
    print(f"  ('{f}', {us}, [{args}], '{e}'),")
print('];')
